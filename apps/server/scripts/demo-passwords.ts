/**
 * Writes `src/store/demo-passwords.ts`: one scrypt hash per demo staff member of their lowercase first name, each with
 * its own salt. Run once and commit the output, so opening a store costs no scrypt work. Prints no password or hash.
 *
 * Committed hashes are kept as they are, and only members missing one are hashed: `verifyCredentials` refuses a demo
 * password with demo sign-in off by comparing the stored hash with the committed one, so a committed hash never changes.
 *
 *   pnpm --filter @meniscus/server exec tsx scripts/demo-passwords.ts
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { hashPassword } from '../src/auth.ts'
import { DEMO_STAFF } from '../src/store/demo-hospital.ts'
import { DEMO_PASSWORD_HASHES } from '../src/store/demo-passwords.ts'

const out = fileURLToPath(new URL('../src/store/demo-passwords.ts', import.meta.url))
const lines: string[] = []
let added = 0
for (const s of DEMO_STAFF) {
  const kept = DEMO_PASSWORD_HASHES[s.id]
  if (kept === undefined) added++
  lines.push(`  ${s.id}: '${kept ?? (await hashPassword(s.username))}',`)
}
writeFileSync(
  out,
  `/** Generated by scripts/demo-passwords.ts. Demo only: each is the scrypt hash of that person's lowercase first name. */
export const DEMO_PASSWORD_HASHES: Record<number, string> = {
${lines.join('\n')}
}
`,
)
console.log(`wrote ${DEMO_STAFF.length} demo hashes, ${added} new`)
